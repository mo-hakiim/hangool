// Writes public/sitemap.xml before each build: every public page, plus the
// published projects, properties and articles when the Supabase settings are
// available (VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY). If Supabase can't be
// reached, the static pages are still written and the build continues.
import { writeFileSync } from "node:fs";

const SITE = "https://hangooldevelopment.com";
const PAGES = [
  ["/", "1.0", "weekly"],
  ["/about", "0.7", "monthly"],
  ["/services", "0.8", "monthly"],
  ["/construction", "0.8", "monthly"],
  ["/real-estate", "0.9", "daily"],
  ["/projects", "0.8", "weekly"],
  ["/gallery", "0.6", "weekly"],
  ["/team", "0.5", "monthly"],
  ["/news", "0.6", "weekly"],
  ["/careers", "0.5", "weekly"],
  ["/contact", "0.7", "yearly"],
  ["/quote", "0.7", "yearly"],
];

const url = (process.env.VITE_SUPABASE_URL ?? "").trim().replace(/\/+$/, "");
const key = (process.env.VITE_SUPABASE_ANON_KEY ?? "").trim();

async function rows(table, cols) {
  if (!/^https:\/\//.test(url) || !key) return [];
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), 8000);
  try {
    const res = await fetch(`${url}/rest/v1/${table}?select=${cols}&published=eq.true`, {
      headers: { apikey: key },
      signal: ctrl.signal,
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return await res.json();
  } catch (e) {
    console.warn(`sitemap: skipped ${table} (${e.message})`);
    return [];
  } finally {
    clearTimeout(timer);
  }
}

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");
const day = (iso) => (iso ? String(iso).slice(0, 10) : undefined);
const entry = (loc, priority, changefreq, lastmod) =>
  `  <url><loc>${esc(SITE + loc)}</loc>${lastmod ? `<lastmod>${lastmod}</lastmod>` : ""}<changefreq>${changefreq}</changefreq><priority>${priority}</priority></url>`;

const [projects, properties, posts] = await Promise.all([
  rows("projects", "id,updated_at"),
  rows("properties", "id,updated_at"),
  rows("blog_posts", "id,updated_at"),
]);

const lines = [
  ...PAGES.map(([p, pr, f]) => entry(p, pr, f)),
  ...projects.map((r) => entry(`/project?id=${r.id}`, "0.6", "monthly", day(r.updated_at))),
  ...properties.map((r) => entry(`/property?id=${r.id}`, "0.7", "weekly", day(r.updated_at))),
  ...posts.map((r) => entry(`/news/post?id=${r.id}`, "0.5", "monthly", day(r.updated_at))),
];

writeFileSync(
  new URL("../public/sitemap.xml", import.meta.url),
  `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by scripts/generate-sitemap.mjs on each build. Do not edit. -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${lines.join("\n")}\n</urlset>\n`,
);
console.log(
  `sitemap: ${PAGES.length} pages, ${projects.length} projects, ${properties.length} properties, ${posts.length} articles`,
);
